#ifndef PREFAB_H
#define PREFAB_H

/* ------------------------------------------------------------------
 * Префабы — модели, которые карта ставит в мир по имени.
 *
 * Префаб — это готовая модель: меш (вершины, UV, индексы) и её текстура.
 * Встроенный префаб "cube" не требует файла: это прежний куб игры, у
 * которого текстура ложится по миру (tile/repeat/stretch). Внешние
 * префабы читаются из .emf (model/emf.h), и имя берётся из самого файла:
 * первым в нём записано название префаба.
 *
 * Реестр кэширует загруженные модели и их текстуры: один .emf читается
 * один раз, сколько бы объектов карты на него ни ссылалось. Текстуры
 * удаляются в prefab_shutdown, поэтому вызывать её нужно, пока контекст
 * OpenGL ещё жив.
 * ------------------------------------------------------------------ */

#include "model/emf.h"
#include "render/prim.h"

#define PREFAB_PATH_MAX 512
#define PREFAB_BUILTIN_CUBE "cube"

typedef struct {
    char name[EMF_NAME_MAX];   /* название префаба, которым он вызывается */
    char file[PREFAB_PATH_MAX];/* путь к .emf; пусто у встроенного куба */
    int builtin_cube;          /* 1 — встроенная модель "cube" */
    EmfMesh mesh;              /* геометрия; у куба пустая */
    const Texture *texture;    /* текстура модели; NULL — текстура карты */

    /* Габариты меша в его собственных координатах: по ним модель
     * вписывается в размер объекта из карты. */
    float min_x, min_y, min_z;
    float max_x, max_y, max_z;
} Prefab;

/* Готовит реестр и регистрирует встроенные префабы (сейчас — "cube").
 * Повторный вызов ничего не делает. */
void prefab_init(void);

/* Освобождает меши и текстуры всех префабов (нужен контекст OpenGL). */
void prefab_shutdown(void);

/* Уже загруженный префаб или NULL. Имя сравнивается без учёта регистра. */
const Prefab *prefab_find(const char *name);

/* Встроенный куб — модель по умолчанию. */
const Prefab *prefab_builtin_cube(void);

/* Сколько уникальных префабов в реестре (для сообщений). */
int prefab_count(void);

/* Префаб по имени из карты.
 *
 * Сначала ищется среди уже загруженных и встроенных. Иначе загрузчик
 * пробует файлы в таком порядке (base_dir — каталог файла карты):
 *
 *   <base_dir><имя>.emf            рядом с картой
 *   <имя>.emf                      текущий каталог
 *   <каталог игры>/<имя>.emf
 *   ... и то же в подкаталогах models/ и assets/models/
 *
 * Имя может быть и путём: 'models/crate.emf' или 'crate.emf'.
 * NULL — префаб не найден или файл не читается (причина — в stderr). */
const Prefab *prefab_get(const char *name, const char *base_dir);

#endif /* PREFAB_H */
