#ifndef EMF_H
#define EMF_H

/* ------------------------------------------------------------------
 * EMF — формат моделей (мешей) игры.
 *
 * Файл бинарный, числа — little-endian, размеры — в байтах.
 *
 * Версия 4 (текущая), заголовок 144 байта:
 *
 *   смещение  размер          поле
 *   0         4               magic "emf\0"
 *   4         4               version = 4 (u32)
 *   8         EMF_NAME_MAX    НАЗВАНИЕ ПРЕФАБА — имя модели (NUL в конце)
 *   ...       EMF_NAME_MAX    имя файла текстуры (пусто — без своей)
 *   ...       4               num_points (u32)
 *   ...       4               num_indices (u32)
 *
 * Далее подряд: вершины (num_points * 3 float), UV (num_points * 2 float),
 * индексы треугольников (num_indices * u32). Индексы — вершины одного
 * треугольника подряд, по три на треугольник.
 *
 * Имя префаба — первое имя в файле: именно им модель вызывается из карты,
 * а имя файла текстуры идёт после него.
 *
 * Версия 3 (старые файлы) читается для совместимости: в её заголовке
 * (80 байт) нет имени префаба, сразу после magic/version идут счётчики,
 * а затем имя текстуры. Такой модели имя даёт имя файла.
 * ------------------------------------------------------------------ */

#include <stdint.h>

#define EMF_MAGIC    "emf"
#define EMF_VERSION  4
#define EMF_NAME_MAX 64   /* длина имени префаба и имени текстуры, с нулём */

typedef struct {
    char name[EMF_NAME_MAX];      /* название префаба (модели) */
    char texture[EMF_NAME_MAX];   /* файл текстуры; пусто — нет своей */
    uint32_t num_points;
    uint32_t num_indices;
    float *points;                /* 3 * num_points: x, y, z */
    float *uvs;                   /* 2 * num_points: u, v */
    uint32_t *indices;            /* num_indices */
} EmfMesh;

/* Читает .emf в mesh (версии 3 и 4). Возвращает 1 при успехе, 0 при ошибке;
 * при ошибке mesh пустой (emf_free не нужен). Проверяются magic, версия,
 * счётчики, размер файла и то, что каждый индекс указывает на вершину:
 * битый файл не приводит к чтению за границей буфера. */
int emf_load(const char *path, EmfMesh *mesh);

/* Записывает mesh в .emf версии 4. Имя префаба и имя текстуры обрезаются
 * до EMF_NAME_MAX - 1 байта. Возвращает 1 при успехе, 0 при ошибке. */
int emf_save(const char *path, const EmfMesh *mesh);

/* Освобождает память меша и обнуляет его. */
void emf_free(EmfMesh *mesh);

#endif /* EMF_H */
