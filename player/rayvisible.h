#ifndef SRV_PLAYER_RAYVISIBLE_H
#define SRV_PLAYER_RAYVISIBLE_H

/* ------------------------------------------------------------------
 * Видимость игроков друг другу: луч между игроками.
 *
 * Игрок A видит игрока B, если отрезок, соединяющий их позиции из
 * последних пакетов [3], не пересекает ни одного куба загруженной
 * карты (--map-file). Позиция из [3] — это центр коллайдера игрока
 * (камера), то есть луч идёт примерно на уровне глаз.
 *
 * Направление взгляда не учитывается: проверяется только перекрытие
 * геометрией. Без загруженной карты геометрии нет и видны все.
 * ------------------------------------------------------------------ */

#include "map/map.h"

/* 1 — from видит to (луч не перекрыт кубами карты), 0 — не видит. */
int ray_player_visible(const SrvMap *map,
                       float from_x, float from_y, float from_z,
                       float to_x, float to_y, float to_z);

#endif /* SRV_PLAYER_RAYVISIBLE_H */
