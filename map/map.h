#ifndef SRV_MAP_H
#define SRV_MAP_H

/* ------------------------------------------------------------------
 * Геометрия карты для расчёта видимости игроков.
 *
 * Загружается файл .tfm — тот же формат, что читает клиент Game3D:
 *
 *     <префаб> x y z sx sy sz [tex=<файл>] [tile=<метры>] [repeat|stretch]
 *
 * Первым в строке идёт имя префаба ("cube" — встроенный куб, любое
 * другое — модель из .emf), числа начинаются со второго токена.
 * Куб занимает пространство от (x, y, z) до (x+sx, y+sy, z+sz) —
 * как в игре (map/map.c), размеры могут быть отрицательными; модель
 * вписывается в тот же AABB. Старые карты, где строка начинается
 * сразу с числа (x y z sx sy sz), тоже читаются — как объект куба.
 * Пустые строки и комментарии с '#' игнорируются, директивы внешнего
 * вида (texture/tex/tile/repeat/stretch) на геометрию не влияют и
 * пропускаются; текстуры серверу не нужны.
 * ------------------------------------------------------------------ */

#include <stddef.h>

/* Осепараллельный параллелепипед в мировых координатах. */
typedef struct {
    float min_x, min_y, min_z;
    float max_x, max_y, max_z;
} SrvBox;

typedef struct {
    SrvBox *boxes;
    size_t count;
    size_t capacity;
} SrvMap;

/* Загружает кубы из файла .tfm. Некорректные строки пропускаются с
 * предупреждением в лог, как это делает клиент. Возвращает 1 при
 * успехе, 0 если файл не открылся или оказался слишком велик. */
int srv_map_load(SrvMap *map, const char *path);

/* Освобождает память кубов; сам SrvMap можно обнулить. */
void srv_map_free(SrvMap *map);

#endif /* SRV_MAP_H */
