#ifndef MAP_H
#define MAP_H

#include <stddef.h>

#include "render/prim.h"    /* Texture: раскладка текстуры по граням куба */
#include "render/texpool.h" /* TexPool: текстуры, загруженные из карты */

/* Как текстура куба ложится на его грани. */
typedef enum {
    /* Рисунок повторяется по миру: одна копия занимает tile метров, соседние
     * кубы продолжают тот же рисунок (плитка, кирпич, трава — по умолчанию). */
    MAP_UV_TILE = 0,
    /* Одна копия растянута на каждую грань целиком: для табличек, экранов,
     * панелей и всего, что должно быть видно целиком, а не «плиткой». */
    MAP_UV_STRETCH
} MapUvMode;

/* Объект куба (осепараллельный параллелепипед / AABB)
 * Позиция (x, y, z), размеры (sx, sy, sz) и своя текстура с её раскладкой.
 */
typedef struct {
    float x, y, z;
    float sx, sy, sz;

    /* Текстура куба: своя из карты или NULL — тогда рисуется текстура,
     * переданная игре в командной строке (Texture в render/render.h).
     * Владелец текстуры — пул текстур карты (map/map.c), куб только ссылается. */
    const Texture *texture;

    /* Сколько метров мира занимает одна копия текстуры (MAP_UV_TILE).
     * 0 — размер по умолчанию, PRIM_TEX_TILE_METERS. */
    float tile;

    MapUvMode uv;
} MapCube;

typedef struct {
    MapCube *cubes;
    size_t count;
    size_t capacity;
    int is_loaded;   /* 1 если карта была успешно загружена из файла, 0 иначе */
    TexPool textures; /* текстуры, загруженные из файла карты */
} Map;

/* Глобальный экземпляр карты мира */
extern Map g_map;

/* Загрузка карты из текстового файла.
 *
 * Строка куба:      x y z sx sy sz [своя текстура и её раскладка]
 * Директивы:        texture <файл> | tile <метры> | repeat | stretch
 * Пустые строки и строки, начинающиеся с '#', игнорируются — как и
 * комментарий в конце строки.
 *
 * Своя текстура куба задаётся как tex=<файл> (или просто путём сразу после
 * размеров), размер копии — tile=<метры>, раскладка — repeat / stretch.
 * Пути относительны файлу карты, затем текущему каталогу.
 * Подробное описание формата — в README.md.
 *
 * Директивы действуют на все кубы, описанные ниже: так одной строкой
 * texture задаётся текстура всей карты, а stretch — только её части.
 *
 * Возвращает 1 при успехе, 0 при ошибке.
 */
int map_load(const char *filename);

/* Инициализация карты в пустом состоянии (освобождает и текстуры) */
void map_init(void);

/* Освобождение ресурсов карты: кубы и текстуры, загруженные из карты.
 * Вызывать, пока контекст OpenGL ещё жив. */
void map_free(void);

/* Проверка, загружена ли пользовательская карта */
int map_is_custom(void);

/* Отрисовка всех объектов карты.
 *
 * fallback — текстура для кубов, которым своя не задана (обычно текстура,
 * переданная игре при запуске). Кубы со своей текстурой рисуются ею.
 * По умолчанию текстура ложится на грани без растяжения, повторяясь по
 * поверхности, — один и тот же рисунок масштабирован на кубах любого
 * размера (см. render/prim.h); куб может попросить stretch или другой
 * размер копии (tile). */
void map_render(const Texture *fallback);

/* Коллизия: проверка попадания точки внутрь кубов карты (с учетом высоты)
 * Возвращает 1, если точка заблокирована кубом, 0 иначе.
 */
int map_point_blocked(float px, float pz, float bottom_y);

/* Проверка блокировки цилиндрического коллайдера игрока кубами карты */
int map_capsule_blocked(float cx, float cz, float feet_y);

/* Высота верхней грани самого высокого куба под точкой (px, pz),
 * находящегося не выше max_y (или вообще под ногами игрока).
 * Если под точкой нет кубов, возвращает default_y.
 */
float map_ground_height(float px, float pz, float current_feet_y, float default_y);

/* Высота верхней грани самого высокого куба под цилиндром коллайдера (cx, cz, radius).
 * Если под цилиндром нет кубов, возвращает default_y.
 */
float map_cylinder_ground_height(float cx, float cz, float radius, float current_feet_y, float default_y);

#endif /* MAP_H */
