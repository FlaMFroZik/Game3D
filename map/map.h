#ifndef MAP_H
#define MAP_H

#include <stddef.h>

#include "model/prefab.h"   /* Prefab: модель, которую ставит карта */
#include "render/prim.h"    /* Texture: раскладка текстуры по граням куба */
#include "render/texpool.h" /* TexPool: текстуры, загруженные из карты */

/* Как текстура куба ложится на его грани. */
typedef enum {
    /* Рисунок повторяется по миру: одна копия занимает tile метров, соседние
     * кубы продолжают тот же рисунок (плитка, кирпич, трава — по умолчанию). */
    MAP_UV_TILE = 0,
    /* Одна копия растянута на каждую грань целиком: для табличек, экранов,
     * панелей и всего, что должно быть видно целиком, а не «плиткой». */
    MAP_UV_STRETCH
} MapUvMode;

/* Объект карты: префаб (модель), поставленный в точку мира.
 *
 * x, y, z — угол осепараллельного параллелепипеда (AABB), sx, sy, sz — его
 * размеры. Для встроенного куба AABB и есть сам куб; модель вписывается
 * в этот параллелепипед целиком, поэтому размеры всегда означают «сколько
 * метров модель занимает в мире», независимо от её собственных единиц.
 * По этому же AABB считаются коллизии.
 */
typedef struct {
    float x, y, z;
    float sx, sy, sz;

    /* Модель, которую рисует объект. NULL трактуется как встроенный куб:
     * загрузчик карты всегда ставит префаб, проверка оставлена на случай
     * объекта, собранного кодом вручную. */
    const Prefab *prefab;

    /* Текстура объекта: своя из карты (tex=...) или NULL — тогда берётся
     * текстура префаба, а если и её нет — текстура, переданная игре.
     * Владельцы текстуры — пулы карты и префабов, объект только ссылается. */
    const Texture *texture;

    /* Сколько метров мира занимает одна копия текстуры (MAP_UV_TILE).
     * 0 — размер по умолчанию, PRIM_TEX_TILE_METERS. Для моделей не
     * используется: у них UV заданы в файле .emf. */
    float tile;

    MapUvMode uv;
} MapObject;

typedef struct {
    MapObject *objects;
    size_t count;
    size_t capacity;
    int is_loaded;   /* 1 если карта была успешно загружена из файла, 0 иначе */
    TexPool textures; /* текстуры, загруженные из файла карты */
} Map;

/* Глобальный экземпляр карты мира */
extern Map g_map;

/* Загрузка карты из текстового файла.
 *
 * Строка объекта:   <префаб> x y z sx sy sz [своя текстура и её раскладка]
 * Директивы:        texture <файл> | tile <метры> | repeat | stretch
 * Пустые строки и строки, начинающиеся с '#', игнорируются — как и
 * комментарий в конце строки.
 *
 * Первым в строке идёт имя префаба: встроенная модель "cube" или модель
 * из .emf (см. model/prefab.h — там же порядок поиска файлов). Своя
 * текстура объекта задаётся как tex=<файл> (или просто путём сразу после
 * размеров), размер копии — tile=<метры>, раскладка — repeat / stretch;
 * для моделей tile/repeat/stretch не действуют, UV у них свои.
 * Пути относительны файлу карты, затем текущему каталогу.
 * Подробное описание формата — в README.md.
 *
 * Старые карты, у которых строка начинается с числа ('x y z sx sy sz'),
 * продолжают работать: такая строка читается как объект встроенного куба.
 *
 * Директивы действуют на все объекты, описанные ниже: так одной строкой
 * texture задаётся текстура всей карты, а stretch — только её части.
 *
 * Возвращает 1 при успехе, 0 при ошибке.
 */
int map_load(const char *filename);

/* Инициализация карты в пустом состоянии (освобождает и текстуры) */
void map_init(void);

/* Освобождение ресурсов карты: кубы и текстуры, загруженные из карты.
 * Вызывать, пока контекст OpenGL ещё жив. */
void map_free(void);

/* Проверка, загружена ли пользовательская карта */
int map_is_custom(void);

/* Отрисовка всех объектов карты.
 *
 * fallback — текстура для объектов, которым своя не задана (обычно
 * текстура, переданная игре при запуске): у куба её нет из карты, у
 * модели — из .emf. Объекты со своей текстурой рисуются ею.
 * У встроенного куба текстура ложится на грани без растяжения, повторяясь
 * по поверхности, — один и тот же рисунок масштабирован на кубах любого
 * размера (см. render/prim.h); куб может попросить stretch или другой
 * размер копии (tile). Модели рисуются своими UV из файла. */
void map_render(const Texture *fallback);

/* Коллизия: проверка попадания точки внутрь объектов карты (с учетом высоты).
 * Для модели проверяется её параллелепипед. Возвращает 1, если точка
 * заблокирована, 0 иначе.
 */
int map_point_blocked(float px, float pz, float bottom_y);

/* Проверка блокировки цилиндрического коллайдера игрока объектами карты */
int map_capsule_blocked(float cx, float cz, float feet_y);

/* Высота верхней грани самого высокого объекта под точкой (px, pz),
 * находящегося не выше max_y (или вообще под ногами игрока).
 * Если под точкой нет объектов, возвращает default_y.
 */
float map_ground_height(float px, float pz, float current_feet_y, float default_y);

/* Высота верхней грани самого высокого объекта под цилиндром коллайдера
 * (cx, cz, radius). Если под цилиндром нет объектов, возвращает default_y.
 */
float map_cylinder_ground_height(float cx, float cz, float radius, float current_feet_y, float default_y);

/* Высота нижней грани самого низкого объекта над точкой (px, pz),
 * находящегося выше current_feet_y.
 * Если над точкой нет объектов, возвращает INFINITY.
 */
float map_ceiling_height(float px, float pz, float current_feet_y);

/* Высота нижней грани самого низкого объекта над цилиндром коллайдера
 * (cx, cz, radius), находящегося выше current_feet_y.
 * Если над цилиндром нет объектов, возвращает INFINITY.
 */
float map_cylinder_ceiling_height(float cx, float cz, float radius, float current_feet_y);

#endif /* MAP_H */
