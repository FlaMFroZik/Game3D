#ifndef GEN_H
#define GEN_H

/* ------------------------------------------------------------------
 * Генерация мира.
 *
 * Мир разбит на чанки — квадраты GEN_CHUNK_SIZE x GEN_CHUNK_SIZE клеток.
 * Высота клетки считается процедурно (детерминированный шум), поэтому
 * рельеф бесконечный и одинаковый независимо от того, загружен чанк
 * или нет. В загруженном чанке высоты лежат в массиве: рендер берёт их
 * оттуда, чтобы не считать шум на каждую вершину каждый кадр.
 * ------------------------------------------------------------------ */

#define GEN_CELL_SIZE            0.25f  /* размер одной клетки в мировых единицах */
#define GEN_CHUNK_SIZE           32     /* клеток по стороне чанка */
#define GEN_CHUNK_VERTS          (GEN_CHUNK_SIZE + 1) /* высоты хранятся с общим краем */
/* Радиус мира вокруг игрока, в чанках. Мир готовится на всю глубину тумана:
 * иначе его край попадает в кадр и видно квадрат загруженных чанков вместо
 * рельефа. Точное значение приходит из рендера (render_view_radius) и
 * ограничено пулом чанков; здесь — границы этого диапазона. */
#define GEN_VIEW_RADIUS_MIN      3      /* минимум: край мира должен быть за концом тумана */
#define GEN_VIEW_RADIUS_MAX      7      /* максимум: (2 * 7 + 1)^2 = 225 <= GEN_MAX_CHUNKS */
#define GEN_MAX_CHUNKS           256    /* размер пула чанков */
#define GEN_MAX_CHUNKS_PER_FRAME 8      /* сколько чанков максимум генерируем за кадр */
#define GEN_TERRAIN_OFFSET       1.0f   /* подъём рельефа над y = 0 */

/* ---------- Высота и её квант ----------
 * Высота узла хранится не «в клетках», а в квантах: GEN_HEIGHT_SUBDIV
 * квантов на клетку. При кванте в целую клетку любой пологий склон
 * рассыпался бы на ступени по GEN_CELL_SIZE — заметно на ровном
 * освещении. Дробный квант делает рельеф гладким, а память та же
 * (один байт на узел). */

#define GEN_HEIGHT_SUBDIV        8                                /* квантов на клетку */
#define GEN_HEIGHT_STEP          (GEN_CELL_SIZE / (float)GEN_HEIGHT_SUBDIV) /* метров на квант */

typedef unsigned char GenHeight;  /* запас: GEN_MAX_HEIGHT * GEN_HEIGHT_SUBDIV <= 255 */

/* ---------- Форма рельефа: равнины с холмами ----------
 * Всё, что измеряется в клетках, — в клетках (одна клетка = GEN_CELL_SIZE). */

#define GEN_MAX_HEIGHT           26     /* верхняя граница рельефа: самый высокий холм */
#define GEN_NOISE_SCALE          80.0f  /* длина волны крупных форм, т.е. ширина холма */
#define GEN_PLAINS_CUTOFF        0.48f  /* что ниже — ровная равнина, без холмов */
#define GEN_PLAINS_GAIN          1.9f   /* как быстро шум после порога превращается в холм */
#define GEN_PLAIN_ROUGH          5      /* пологие волны равнины, чтобы она не была «столом» */
#define GEN_RELIEF_FLOOR         0.35f  /* холмы на «пустых» участках (0 = чистая равнина) */

/* Квант рельефа по высоте: 1 — без террас, рельеф гладкий;
 * 3 и больше — плоские площадки со стенками выше шага игрока. */
#define GEN_TERRACE_STEP         1
#define GEN_TERRACE_ROUGH        0      /* разброс высоты внутри террасы, в клетках */

typedef struct {
    int cx, cz;                                             /* координаты чанка */
    GenHeight height[GEN_CHUNK_VERTS][GEN_CHUNK_VERTS];     /* высота узла в квантах */
} Chunk;

/* ---------- Пул чанков ---------- */

void          gen_init(void);
int           gen_chunk_count(void);           /* число загруженных чанков */
const Chunk  *gen_chunk_at(int index);         /* NULL, если индекса нет */
Chunk        *gen_find_chunk(int cx, int cz);  /* NULL, если чанк не загружен */

/* Радиус мира вокруг игрока в метрах: сколько нужно, чтобы кадр не обрывался
 * на краю тумана. Значение переводится в чанки и ограничивается пулом, так
 * что вызывать можно с любым разумным числом (в том числе каждый кадр). */
void gen_set_view_radius(float meters);

/* Текущий радиус мира в чанках (для отладки и тестов). */
int  gen_view_radius(void);

/* Догружает чанки вокруг точки мира и выгружает ушедшие далеко. */
void gen_update_chunks(float cam_x, float cam_z);

/* ---------- Высоты ---------- */

int   gen_cell_height(int wx, int wz);         /* высота клетки, в квантах высоты */
float gen_sample_height(float x, float z);     /* высота рельефа в мире (билинейно) */

/* Высота угла внутри чанка, lx/lz в [0 .. GEN_CHUNK_SIZE], в мировых единицах. */
float gen_chunk_y(const Chunk *c, int lx, int lz);

/* ---------- Координаты ---------- */

int gen_floor_div(int a, int b);               /* деление с округлением вниз */
int gen_chunk_coord(int cell);                 /* клетка -> номер чанка */
int gen_world_to_cell(float w);                /* мир -> номер клетки */

#endif
