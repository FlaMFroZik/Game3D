#ifndef MAP_LIST_H
#define MAP_LIST_H

/* ------------------------------------------------------------------
 * Список карт рядом с игрой.
 *
 * Карты ищутся в каталоге исполняемого файла (exe / ELF), а не в текущем
 * каталоге: игру запускают из любого места, и меню должно показывать её
 * собственные карты. В список попадают файлы .map и .txt.
 * ------------------------------------------------------------------ */

#include <stddef.h>

#define MAP_LIST_MAX       64   /* сколько карт показываем в меню */
#define MAP_LIST_NAME_MAX  128  /* длина имени файла */
#define MAP_LIST_PATH_MAX  512  /* длина полного пути */

typedef struct {
    char dir[MAP_LIST_PATH_MAX];                 /* каталог, из которого собран список */
    char names[MAP_LIST_MAX][MAP_LIST_NAME_MAX]; /* имена файлов, по алфавиту */
    int count;
} MapList;

/* Каталог, в котором лежит исполняемый файл игры; ".", если определить
 * его не удалось. Строка живёт до конца программы. */
const char *map_list_game_dir(void);

/* Собирает файлы карт из каталога: без скрытых файлов и каталогов,
 * имена сортируются по алфавиту. Возвращает число найденных карт
 * (не больше MAP_LIST_MAX). */
int map_list_scan(MapList *list, const char *dir);

/* Полный путь к карте с номером index — его можно передать в map_load.
 * При неверном номере записывает пустую строку. */
void map_list_path(const MapList *list, int index, char *out, size_t out_size);

#endif /* MAP_LIST_H */
