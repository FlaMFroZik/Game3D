#ifndef SRV_COMMANDS_H
#define SRV_COMMANDS_H

/* ------------------------------------------------------------------
 * Команды управления со stdin: help, status, list, kick <id>, quit.
 *
 * Отдельный поток блокирующе читает stdin (на Windows select() умеет
 * ждать только сокеты) и складывает строки в небольшую очередь; главный
 * цикл сервера забирает их через commands_poll(). Закрытый stdin — не
 * ошибка: сервер продолжает работать без интерактивных команд.
 * ------------------------------------------------------------------ */

#include "server.h"

/* Создаёт очередь и запускает поток чтения stdin.
 * Возвращает 1 при успехе, 0 — поток не запустился (команды будут
 * недоступны, сервер продолжает работу). */
int commands_init(void);

/* Выполняет все накопленные команды. Вызывается из главного цикла. */
void commands_poll(SrvServer *server);

#endif /* SRV_COMMANDS_H */
