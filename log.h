#ifndef SRV_LOG_H
#define SRV_LOG_H

/* ------------------------------------------------------------------
 * Лог сервера: события с меткой времени в stdout.
 *
 * Уровень задаётся один раз при старте из флагов командной строки:
 * по умолчанию INFO, -q оставляет только ошибки, -v включает отладку.
 * ------------------------------------------------------------------ */

typedef enum {
    SRV_LOG_ERROR = 0,  /* ошибки — печатаются всегда */
    SRV_LOG_INFO  = 1,  /* обычные события: вход/выход, тайм-ауты */
    SRV_LOG_DEBUG = 2   /* каждая датаграмма — только с -v */
} SrvLogLevel;

void srv_log_init(SrvLogLevel level);
void srv_log(SrvLogLevel level, const char *format, ...);

#endif /* SRV_LOG_H */
