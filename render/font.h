#ifndef FONT_H
#define FONT_H

/* ------------------------------------------------------------------
 * Текст для интерфейса.
 *
 * Глифы запекаются из TrueType-файла готовой библиотекой stb_truetype
 * (single-header, public domain) в один атлас, а рисуются обычными
 * текстурированными квадами фиксированного конвейера — шейдеров и
 * отдельных библиотек текста не нужно.
 *
 * Покрытие: печатный ASCII, русские буквы А-Яа-я и Ёё. Неизвестный
 * символ рисуется квадратом-заглушкой, чтобы текст не «съезжал».
 * ------------------------------------------------------------------ */

#include <GL/gl.h>

/* Высота строки, под которую запекается атлас, в пикселях окна.
 * Рисуется текст с любым масштабом (см. scale у font_draw), поэтому
 * значение задаёт только качество: крупнее — чётче при увеличении. */
#define FONT_PIXEL_SIZE 32.0f

/* Шрифт вместе с атласом в видеопамяти. */
typedef struct Font Font;

/* Читает TrueType-файл, печёт атлас и загружает его в OpenGL.
 * Вызывать, когда контекст OpenGL уже текущий.
 * NULL — файл не найден, не читается или в нём нет нужных глифов. */
Font *font_create(const char *ttf_path, float pixel_size);

/* Освобождает атлас. Нужен текущий контекст OpenGL. */
void font_destroy(Font *font);

/* Ширина строки в пикселях окна при данном масштабе. */
float font_text_width(const Font *font, const char *utf8, float scale);

/* Высота строки в пикселях окна при данном масштабе. */
float font_line_height(const Font *font, float scale);

/* Рисует строку: x, y — левый верхний угол строки в пикселях окна
 * (ось Y вниз), rgba — цвет текста. Неизвестные глифы рисуются
 * квадратом, поэтому ширина строки совпадает с font_text_width. */
void font_draw(const Font *font, float x, float y, float scale,
               const float rgba[4], const char *utf8);

#endif /* FONT_H */
