#ifndef TEXPOOL_H
#define TEXPOOL_H

/* ------------------------------------------------------------------
 * Пул текстур.
 *
 * Карта может задать свою текстуру каждому кубу, и один и тот же файл
 * часто указан у десятков кубов. Пул держит загруженные текстуры по
 * путям и отдаёт уже готовую, вместо повторной загрузки в видеопамять:
 * файл читается один раз, а кубы просто ссылаются на одну текстуру.
 *
 * Пул владеет текстурами: освобождать их по отдельности не нужно.
 * Текстуры удаляются из видеопамяти в texpool_free, поэтому его нужно
 * вызывать, пока контекст OpenGL ещё жив.
 * ------------------------------------------------------------------ */

#include <stddef.h>

#include "render/prim.h"

/* Максимальная длина пути текстуры, включая завершающий ноль. */
#define TEXPOOL_PATH_MAX 512

typedef struct {
    Texture tex;    /* текстура в видеопамяти */
    char   *path;   /* путь, по которому она была загружена */
} TexPoolEntry;

typedef struct {
    /* Записи лежат отдельными блоками, чтобы указатели на Texture
     * не «переезжали» при росте таблицы: карта хранит их у себя. */
    TexPoolEntry **entries;
    size_t count;
    size_t capacity;
} TexPool;

/* Пустой пул. Повторный вызов на непустом пуле ничего не освобождает. */
void texpool_init(TexPool *pool);

/* Удаляет все текстуры пула (нужен текущий контекст OpenGL). */
void texpool_free(TexPool *pool);

/* Сколько текстур уже загружено. */
size_t texpool_count(const TexPool *pool);

/* Текстура по пути: уже загруженная берётся из пула, новая читается с диска.
 * NULL — загрузить не удалось (пустой путь, файл не найден или битый).
 * Неудача не запоминается: файл могут поправить и перезапустить игру. */
const Texture *texpool_get(TexPool *pool, const char *path);

/* Уже загруженная текстура по пути или NULL (без обращения к диску). */
const Texture *texpool_find(const TexPool *pool, const char *path);

#endif /* TEXPOOL_H */
