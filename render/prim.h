#ifndef PRIM_H
#define PRIM_H

/* ------------------------------------------------------------------
 * Примитивы: текстуры и геометрия одной клетки рельефа.
 * Модуль ничего не знает про мир и камеру — только про OpenGL.
 * ------------------------------------------------------------------ */

#include <GL/gl.h>

/* Загружает .raw-текстуру в видеопамять. 0 — ошибка (файл или память). */
GLuint prim_load_texture(const char *filename);

/* Освобождает текстуру, созданную prim_load_texture. */
void prim_free_texture(GLuint tex);

/* Четыре угла клетки: (x0,z0)-(x1,z1), высоты y00/y10/y01/y11. */
typedef struct {
    float x0, z0;   /* дальний (по X и Z) угол клетки */
    float x1, z1;   /* ближний угол клетки */
    float y00, y10; /* высоты дальнего и ближнего угла по X */
    float y01, y11; /* высоты дальнего и ближнего угла по X + 1 по Z */
} CellQuad;

/* Рисует клетку как два треугольника с текстурными координатами. */
void prim_draw_cell(const CellQuad *q);

#endif
