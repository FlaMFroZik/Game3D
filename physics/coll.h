#ifndef COLL_H
#define COLL_H

/* ------------------------------------------------------------------
 * Коллизии игрока с рельефом и объектами карты.
 *
 * Игрок — вертикальный цилиндр (радиус COLL_RADIUS, высота COLL_HEIGHT).
 * Рельеф проверяется в точках по окружности коллайдера: точка считается
 * стеной, если земля в ней выше ног игрока больше чем на COLL_STEP_HEIGHT,
 * либо если рядом резкий перепад высоты (обрыв) выше уровня ног.
 * ------------------------------------------------------------------ */

#define COLL_RADIUS      0.4f   /* радиус коллайдера */
#define COLL_HEIGHT      1.8f   /* высота коллайдера (камера — его середина) */
#define COLL_STEP_HEIGHT 1.0f   /* максимальная высота подъёма за один шаг */
#define COLL_EPSILON     0.01f  /* запас, чтобы не залипать в рельефе */

/* Установка текущего уровня ног игрока (для корректной проверки высоты над кубами). */
void coll_set_feet_y(float feet_y);

/* Высота земли под точкой мира. */
float coll_ground_height(float x, float z);

/* Мешает ли рельеф точке на высоте bottom_y. */
int coll_point_blocked(float px, float pz, float bottom_y);

/* Упирается ли коллайдер с центром (cx, cz) и низом feet_y в рельеф. */
int coll_capsule_blocked(float cx, float cz, float feet_y);

/* Горизонтальное перемещение со скольжением: оси пробуются по отдельности,
 * поэтому у стены игрок скользит вдоль неё, а не останавливается. */
void coll_move(float *x, float *z, float dx, float dz, float feet_y);

#endif
